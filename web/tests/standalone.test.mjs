import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,readFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {startServer} from '../standalone/server.mjs';
const password='test-only-passphrase-789';
test('standalone authentication, persistence, version restore, MCP tokens and subpath isolation',async()=>{
 const dir=await mkdtemp(join(tmpdir(),'shuye-server-'));let app;
 const origin='http://127.0.0.1:18789',base='/shuye';
 const opts={directory:dir,publicDirectory:fileURLToPath(new URL('../public',import.meta.url)),origin,basePath:base,port:18789,bootstrapPassword:password};
 const req=(path,options={})=>fetch(origin+base+path,{redirect:'manual',...options});
 const post=(path,body,cookie,extra={})=>req(path,{method:'POST',headers:{origin,...(cookie?{cookie}:{}),...extra},body});
 try{
  app=await startServer(opts);
  assert.equal((await post('/api/mcp-projects','{}',null,{'oai-authenticated-user-id':'admin'})).status,401);
  assert.equal((await post('/login','password='+password,null,{origin:'https://evil.example'})).status,403);
  assert.equal((await req('/login',{method:'POST',body:'password='+password})).status,403);
  assert.equal((await post('/login','password=incorrect')).status,401);
  const login=await post('/login','password='+password);assert.equal(login.status,303);
  const cookie=login.headers.get('set-cookie').split(';')[0];assert.match(login.headers.get('set-cookie'),/HttpOnly; SameSite=Strict/);
  assert.match(await (await req('/config.js')).text(),/\/shuye/);
  const editor=await req('/editor/index.html');assert.equal(editor.status,200);assert.match(await editor.text(),/class="back-library" href="\/shuye\/"/);
  assert.deepEqual(await(await req('/api/session',{headers:{cookie}})).json(),{user:'admin'});
  const api=async(tool,args={})=>{const r=await post('/api/mcp-projects',JSON.stringify({tool,arguments:args}),cookie);return {status:r.status,value:await r.json()};};
  assert.equal((await api('create_project',{projectId:'acceptance',title:'独立服务器'})).value.revision,1);
  assert.equal((await api('apply_changes',{projectId:'acceptance',expectedRevision:1,operations:[{op:'set_title',title:'修改后'}]})).value.revision,2);
  assert.equal((await api('apply_changes',{projectId:'acceptance',expectedRevision:1,operations:[{op:'set_title',title:'冲突'}]})).status,409);
  assert.equal((await api('restore_version',{projectId:'acceptance',expectedRevision:2,revision:1})).value.revision,3);
  const tokenHTML=await(await post('/account/token','',cookie)).text();const token=tokenHTML.match(/<pre>([A-Za-z0-9_-]{43})<\/pre>/)[1];
  const rpc=()=>req('/mcp',{method:'POST',headers:{authorization:'Bearer '+token},body:JSON.stringify({jsonrpc:'2.0',id:1,method:'tools/call',params:{name:'list_projects',arguments:{}}})});
  assert.equal((await(await rpc()).json()).result.structuredContent.projects.length,1);
  const list=await req('/mcp',{method:'POST',headers:{authorization:'Bearer '+token},body:JSON.stringify({jsonrpc:'2.0',id:2,method:'tools/list'})});assert.equal((await list.json()).result.tools.length,84);
  assert.equal((await post('/account/token','',cookie,{authorization:'Bearer '+token})).status,303);
  assert.equal((await req('/%2e%2e%2fserver.mjs')).status,404);
  assert.equal((await req('/.env')).status,404);
  await app.close();app=await startServer({...opts,bootstrapPassword:undefined});
  assert.equal((await api('get_project',{projectId:'acceptance'})).value.document.title,'独立服务器');
  assert.equal((await(await rpc()).json()).result.structuredContent.projects[0].revision,3);
  const account=await(await req('/account',{headers:{cookie}})).text(),tokenId=account.match(/name="id" value="([a-f0-9]{64})"/)[1];
  await post('/account/revoke','id='+tokenId,cookie);assert.equal((await rpc()).status,401);
  await post('/account/password',new URLSearchParams({password,newPassword:'new-test-password-456'}).toString(),cookie);
  assert.equal((await req('/api/session',{headers:{cookie}})).status,200);assert.equal((await(await req('/api/session',{headers:{cookie}})).json()).user,null);
  assert.equal((await post('/login','password='+password)).status,401);
  const newLogin=await post('/login','password=new-test-password-456');assert.equal(newLogin.status,303);
  const fresh=newLogin.headers.get('set-cookie').split(';')[0];await post('/signout-with-chatgpt','',fresh);assert.equal((await(await req('/api/session',{headers:{cookie:fresh}})).json()).user,null);
 }finally{if(app)await app.close();await rm(dir,{recursive:true,force:true});}
});
